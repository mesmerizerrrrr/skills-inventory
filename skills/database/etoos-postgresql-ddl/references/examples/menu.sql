    menu_no             bigint generated by default as identity primary key,
    parnts_menu_no      bigint        null,
    menu_tp             varchar(10)   not null,
    brnch_cd            varchar(4)    null,
    menu_nm             varchar(10)   not null,
    link_url            varchar(5000) not null,
    link_tgt_tp         varchar(5)    not null default 'SELF',
    lisorc_file_no      bigint        null,
    sort_seq            smallint      not null,
    use_yn              varchar(1)    not null default 'N',
    brnch_tp_exposr_bit smallint      not null default 0,
    user_tp_exposr_bit  smallint      not null default 0,
    reg_dtm             timestamp(6)  not null default now(),
    reger_id            varchar(50)   not null default 'SYSTEM',
    upd_dtm             timestamp(6)  not null default now(),
    updpsn_id           varchar(50)   not null default 'SYSTEM'
);
